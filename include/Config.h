// The Wokwi screen is a LANDSCAPE 320x240 panel, and the 135x240 frame is drawn
// as a centered portrait strip inside it. That needs a LANDSCAPE logical display
// (rotation 0 or 2). Rotations 1/3 make the logical display portrait (240x320),
// which shows the whole UI sideways on this landscape panel.
// Wokwi does not reliably honor the 0<->2 flip bits, so the 180 deg correction
