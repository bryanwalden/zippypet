#!/usr/bin/env python3
"""
scripts/build_sprites.py
Reads PNG sprite sheets from an assets/ folder, slices them into 32x32 frames,
converts pixels to RGB565 (treating #FF00FF as transparent), and generates
include/GeneratedSprites.h.
"""

import os
import sys
import glob
from PIL import Image

FRAME_W = 32
FRAME_H = 32
CHROMA_KEY = 0xF81F  # RGB565 representation of #FF00FF (r=31, g=0, b=31)

def to_rgb565(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    val = (r5 << 11) | (g6 << 5) | b5
    if val == CHROMA_KEY:
        val = 0xF81E  # Shift slightly so it is not treated as transparent
    return val

def is_transparent_pixel(p):
    """
    Check if pixel is transparent:
    - Alpha channel < 128
    - Or color matches magenta #FF00FF (r>=200, g<=50, b>=200)
    """
    if len(p) == 4:
        r, g, b, a = p
        if a < 128:
            return True
    else:
        r, g, b = p[:3]
    return (r >= 200 and g <= 50 and b >= 200)

def process_sprite_sheet(image_path):
    sheet_name = os.path.splitext(os.path.basename(image_path))[0]
    # Clean sheet name for C identifier
    clean_name = "".join(c if (c.isalnum() or c == '_') else '_' for c in sheet_name).lower()
    
    with Image.open(image_path) as img:
        img_w, img_h = img.size
        cols = img_w // FRAME_W
        rows = img_h // FRAME_H
        
        if cols == 0 or rows == 0:
            print(f"Skipping {image_path}: smaller than {FRAME_W}x{FRAME_H}")
            return None
        
        frames = []
        frame_idx = 0
        for r in range(rows):
            for c in range(cols):
                box = (c * FRAME_W, r * FRAME_H, (c + 1) * FRAME_W, (r + 1) * FRAME_H)
                tile = img.crop(box)
                
                # Convert tile pixels to RGB565
                pixels_565 = []
                for y in range(FRAME_H):
                    for x in range(FRAME_W):
                        pix = tile.getpixel((x, y))
                        if is_transparent_pixel(pix):
                            pixels_565.append(CHROMA_KEY)
                        else:
                            r_c, g_c, b_c = pix[:3]
                            pixels_565.append(to_rgb565(r_c, g_c, b_c))
                
                frames.append((f"{clean_name}_frame{frame_idx}", pixels_565))
                frame_idx += 1
                
        return clean_name, frames

def main():
    workspace_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    assets_dir = os.path.join(workspace_root, "assets")
    output_header = os.path.join(workspace_root, "include", "GeneratedSprites.h")
    
    # Priority sprite sheet files to look for
    sheet_files = []
    # 1. Search assets/ directly
    for fname in sorted(os.listdir(assets_dir)):
        if fname.lower().endswith(".png") and not fname.startswith("raw_") and not fname.startswith("crop") and not fname.startswith("lcd_"):
            full_p = os.path.join(assets_dir, fname)
            if os.path.isfile(full_p):
                sheet_files.append(full_p)
                
    # 2. Search assets/sprites/ if not already present
    sprites_sub = os.path.join(assets_dir, "sprites")
    if os.path.isdir(sprites_sub):
        for fname in sorted(os.listdir(sprites_sub)):
            if fname.lower().endswith(".png") and not fname.startswith("sprite_roster"):
                full_p = os.path.join(sprites_sub, fname)
                if os.path.isfile(full_p) and full_p not in sheet_files:
                    # Only add if base name not already found in assets_dir
                    base = os.path.basename(full_p)
                    if not any(os.path.basename(f) == base for f in sheet_files):
                        sheet_files.append(full_p)

    print(f"Discovered {len(sheet_files)} sprite sheet(s) in {assets_dir}:")
    for f in sheet_files:
        print(f"  - {os.path.basename(f)}")

    all_sheets = {}
    for f in sheet_files:
        res = process_sprite_sheet(f)
        if res:
            clean_name, frames = res
            all_sheets[clean_name] = frames

    os.makedirs(os.path.dirname(output_header), exist_ok=True)
    with open(output_header, "w", encoding="utf-8") as out:
        out.write("#pragma once\n\n")
        out.write("#include <Arduino.h>\n\n")
        out.write("// Auto-generated by scripts/build_sprites.py\n")
        out.write("// 32x32 RGB565 sprites with #FF00FF (0xF81F) transparent chroma key\n\n")
        out.write(f"#define SPRITE_WIDTH         {FRAME_W}\n")
        out.write(f"#define SPRITE_HEIGHT        {FRAME_H}\n")
        out.write(f"#define SPRITE_CHROMA_KEY    0x{CHROMA_KEY:04X}\n\n")
        
        out.write("struct SpriteInfo {\n")
        out.write("    const uint16_t* data;\n")
        out.write("    int width;\n")
        out.write("    int height;\n")
        out.write("};\n\n")

        # Emit pixel data arrays
        for clean_name, frames in all_sheets.items():
            out.write(f"// ==========================================\n")
            out.write(f"// Sheet: {clean_name} ({len(frames)} frames of 32x32)\n")
            out.write(f"// ==========================================\n")
            for frame_name, pixels in frames:
                out.write(f"static const uint16_t PROGMEM {frame_name}[{FRAME_W * FRAME_H}] = {{\n")
                for i in range(0, len(pixels), 12):
                    chunk = pixels[i:i+12]
                    chunk_str = ", ".join(f"0x{v:04X}" for v in chunk)
                    if i + 12 < len(pixels):
                        out.write(f"    {chunk_str},\n")
                    else:
                        out.write(f"    {chunk_str}\n")
                out.write("};\n\n")
                
            # Frame pointer array
            frame_ptrs = ", ".join(f"{fn}" for fn, _ in frames)
            out.write(f"static const uint16_t* const {clean_name}_frames[{len(frames)}] = {{ {frame_ptrs} }};\n")
            out.write(f"static const uint8_t {clean_name}_frame_count = {len(frames)};\n\n")

        # Helper lookups for pet stages (egg = 0, stages 1..7)
        out.write("// ==========================================\n")
        out.write("// Stage Sprites Lookup\n")
        out.write("// ==========================================\n")
        out.write("inline const uint16_t* getStageFrame(uint8_t stage, uint8_t frameIdx = 0) {\n")
        out.write("    switch (stage) {\n")
        out.write("        case 0:\n")
        out.write("            return egg_frames[frameIdx % egg_frame_count];\n")
        for lvl in range(1, 8):
            name = f"cerato_lv{lvl}"
            if name in all_sheets:
                out.write(f"        case {lvl}:\n")
                out.write(f"            return {name}_frames[frameIdx % {name}_frame_count];\n")
        out.write("        default:\n")
        out.write("            return cerato_lv1_frames[0];\n")
        out.write("    }\n")
        out.write("}\n\n")

        out.write("inline uint8_t getStageFrameCount(uint8_t stage) {\n")
        out.write("    switch (stage) {\n")
        out.write("        case 0:\n")
        out.write("            return egg_frame_count;\n")
        for lvl in range(1, 8):
            name = f"cerato_lv{lvl}"
            if name in all_sheets:
                out.write(f"        case {lvl}:\n")
                out.write(f"            return {name}_frame_count;\n")
        out.write("        default:\n")
        out.write("            return 1;\n")
        out.write("    }\n")
        out.write("}\n\n")

        # Backward compatibility definitions for any old code
        out.write("// Backward compatibility aliases\n")
        for lvl in range(1, 8):
            name = f"cerato_lv{lvl}"
            if name in all_sheets:
                out.write(f"static const SpriteInfo {name}_walk1 = {{ {name}_frames[0], 32, 32 }};\n")
                out.write(f"static const SpriteInfo {name}_walk2 = {{ {name}_frames[{min(1, len(all_sheets[name])-1)}], 32, 32 }};\n")
                out.write(f"static const SpriteInfo {name}_roar  = {{ {name}_frames[{min(2, len(all_sheets[name])-1)}], 32, 32 }};\n")
                out.write(f"static const SpriteInfo {name}_sleep = {{ {name}_frames[{min(3, len(all_sheets[name])-1)}], 32, 32 }};\n")

    print(f"\nSuccessfully generated {output_header}!")
    print(f"Header size: {os.path.getsize(output_header) / 1024:.1f} KB")

if __name__ == "__main__":
    main()
